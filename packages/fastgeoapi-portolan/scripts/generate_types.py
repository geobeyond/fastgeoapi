"""Generate the document types of the reader from the bundled JSON Schemas.

Usage: python scripts/generate_types.py [--check]

TypedDicts go to ``fastgeoapi_portolan/catalog/_generated/``, Pydantic models to
``fastgeoapi_portolan/models/``. With ``--check`` nothing is written: the script
exits 1 when the committed files differ from a fresh generation.

The TypedDicts must import on Python 3.10 without ``typing_extensions``, where
the generator takes ``NotRequired`` and, for some schemas, ``TypedDict``. In a
class body the annotations stay strings, so ``NotRequired`` moves under
``TYPE_CHECKING`` and ``TypedDict`` comes from ``typing``. In the functional
form, used for keys such as ``table:columns``, the values are evaluated at
import, so those calls lose ``NotRequired`` and ``closed=True`` and become
``total=False`` instead. isort and black then format the result, as the
generator formats its own output. Their types become strings, which
``TypedDict`` keeps as forward references: the generator writes some types
before the names they use.

web-map-links is not generated: it defines ``pmtiles:layers`` under a
condition the generator cannot follow, and ``catalog/types.py`` types it.
"""

from __future__ import annotations

import argparse
import ast
import filecmp
import re
import subprocess  # ruff: ignore[suspicious-subprocess-import]
import sys
import tempfile
from pathlib import Path

PACKAGE = Path(__file__).parent.parent / "fastgeoapi_portolan"
SCHEMAS = PACKAGE / "catalog" / "schemas"
TYPES = PACKAGE / "catalog" / "_generated"
MODELS = PACKAGE / "models"

STAC = "stac/1.1.0"
EXTENSIONS = "extensions/stac-extensions.github.io"
INPUTS = {
    "catalog": f"{STAC}/catalog-spec/json-schema/catalog.json",
    "collection": f"{STAC}/collection-spec/json-schema/collection.json",
    "item": f"{STAC}/item-spec/json-schema/item.json",
    "table": f"{EXTENSIONS}/table/v1.2.0/schema.json",
    "file": f"{EXTENSIONS}/file/v2.1.0/schema.json",
    "alternate_assets": f"{EXTENSIONS}/alternate-assets/v1.2.0/schema.json",
    "partition": "extensions/schemas.portolan-sdi.org/incubating/partition/v1.0.0/schema.json",
}
COMMON = [
    "--input-file-type",
    "jsonschema",
    "--target-python-version",
    "3.10",
    "--disable-timestamp",
    # Documents hold date-times as strings; the schemas also give them a
    # `pattern`, which pydantic cannot apply to a datetime.
    "--type-mappings",
    "string+date-time=string",
    "--formatters",
    "black",
    "isort",
]
TYPED_DICT = ["--output-model-type", "typing.TypedDict"]
PYDANTIC = [
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--extra-fields",
    "allow",
    "--use-annotated",
]
GENERATED_INIT = (
    '"""Generated by ``scripts/generate_types.py`` from the bundled schemas; do not edit."""\n'
)
BACKPORT_IMPORT = re.compile(r"^from typing_extensions import (?P<names>.+)$", re.MULTILINE)
CHECKER_ONLY = {"NotRequired", "Required"}
FORMATTERS = (
    ["isort", "--profile", "black", "-q"],
    ["black", "-q", "--target-version", "py310"],
)


def _run(arguments: list[str]) -> None:
    subprocess.run(  # ruff: ignore[subprocess-without-shell-equals-true] # nosec B603
        [sys.executable, "-m", *arguments], check=True
    )


def _generate(schema: Path, target: Path, flags: list[str]) -> None:
    _run(
        [
            "datamodel_code_generator",
            "--input",
            str(schema),
            *COMMON,
            *flags,
            "--output",
            str(target),
        ]
    )


def _field_type(value: ast.expr) -> str:
    """The type of a functional field as a string, without its ``NotRequired``."""
    if isinstance(value, ast.Subscript) and ast.unparse(value.value) == "NotRequired":
        value = value.slice
    return repr(ast.unparse(value))


def _functional_with_string_types(source: str) -> str:
    """Rebuild every functional ``TypedDict(...)`` with string types and ``total=False``.

    A string is a forward reference, which ``TypedDict`` keeps without
    evaluating it: the generator writes some types before the names they
    use, and ``NotRequired`` would need ``typing_extensions`` on 3.10.
    """
    offsets = [0]
    for line in source.splitlines(keepends=True):
        offsets.append(offsets[-1] + len(line))
    calls = [
        node.value
        for node in ast.parse(source).body
        if isinstance(node, ast.Assign)
        and isinstance(node.value, ast.Call)
        and ast.unparse(node.value.func) == "TypedDict"
    ]
    for call in sorted(calls, key=lambda node: node.lineno, reverse=True):
        name, fields = call.args[0], call.args[1]
        if not isinstance(fields, ast.Dict) or call.end_lineno is None:
            raise SystemExit(f"unexpected TypedDict form at line {call.lineno}")
        items = ", ".join(
            f"{ast.unparse(key)}: {_field_type(value)}"
            for key, value in zip(fields.keys, fields.values, strict=True)
            if key is not None
        )
        rebuilt = f"TypedDict({ast.unparse(name)}, {{{items}}}, total=False)"
        start = offsets[call.lineno - 1] + call.col_offset
        end = offsets[call.end_lineno - 1] + call.end_col_offset
        source = source[:start] + rebuilt + source[end:]
    return source


def _without_backport_imports(source: str) -> str:
    """Take from ``typing`` what it has, and leave the rest to the type checker."""

    def replace(match: re.Match[str]) -> str:
        names = [name.strip() for name in match["names"].split(",")]
        rest = source[match.end() :]
        runtime = [name for name in names if name not in CHECKER_ONLY]
        checker = [name for name in names if name in CHECKER_ONLY and name in rest]
        lines = [f"from typing import {', '.join(runtime)}"] if runtime else []
        if checker:
            lines += ["from typing import TYPE_CHECKING", "", "if TYPE_CHECKING:"]
            lines.append(f"    from typing_extensions import {', '.join(checker)}")
        return "\n".join(lines)

    return BACKPORT_IMPORT.sub(replace, source)


def _typed_dicts_for_python_3_10(path: Path) -> None:
    source = _functional_with_string_types(path.read_text(encoding="utf-8"))
    path.write_text(_without_backport_imports(source), encoding="utf-8")
    for formatter in FORMATTERS:
        _run([*formatter, str(path)])


def _write_all(types: Path, models: Path) -> None:
    types.mkdir(parents=True, exist_ok=True)
    models.mkdir(parents=True, exist_ok=True)
    generated = [*types.glob("*.py"), *(p for p in models.glob("*.py") if p.name != "__init__.py")]
    for path in generated:
        path.unlink()
    (types / "__init__.py").write_text(GENERATED_INIT, encoding="utf-8")
    for name, relative in INPUTS.items():
        schema = SCHEMAS / relative
        _generate(schema, types / f"{name}.py", TYPED_DICT)
        _typed_dicts_for_python_3_10(types / f"{name}.py")
        _generate(schema, models / f"{name}.py", PYDANTIC)


def _names(directory: Path) -> list[str]:
    names = [f"{name}.py" for name in INPUTS]
    return [*names, "__init__.py"] if directory.name == "_generated" else names


def main() -> None:
    """Regenerate the types and models, or check them with ``--check``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    if not check:
        _write_all(TYPES, MODELS)
        return
    with tempfile.TemporaryDirectory() as tmp:
        fresh_types, fresh_models = Path(tmp) / "_generated", Path(tmp) / "models"
        _write_all(fresh_types, fresh_models)
        stale = [
            str(committed.relative_to(PACKAGE))
            for fresh, committed_dir in ((fresh_types, TYPES), (fresh_models, MODELS))
            for name in _names(fresh)
            if not (committed := committed_dir / name).is_file()
            or not filecmp.cmp(fresh / name, committed, shallow=False)
        ]
    if stale:
        print("stale, run `nox -s portolan-types`:", *stale, sep="\n  ")
        sys.exit(1)
    print("types and models are up to date")


if __name__ == "__main__":
    main()
